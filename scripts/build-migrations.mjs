#!/usr/bin/env node
/**
 * v192 · Bundles db/migrations/*.sql into lib/server/migrationsBundle.ts, so the server applies them by itself at
 * start-up (lib/server/migrations.ts) without reading files at run time. Run after adding or changing a migration:
 *   node scripts/build-migrations.mjs        (writes the bundle)
 *   node scripts/build-migrations.mjs --check (fails if the bundle is out of date; used by the tests)
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const files = readdirSync("db/migrations").filter((f) => /^\d{3}-[a-z0-9-]+\.sql$/.test(f)).sort();
const list = files.map((file) => {
  const sql = readFileSync(`db/migrations/${file}`, "utf8");
  return { id: file.slice(0, 3), file, sha256: createHash("sha256").update(sql).digest("hex"), sql };
});
const out = `// GENERATED by scripts/build-migrations.mjs from db/migrations/*.sql — do not edit by hand.
export type BundledMigration = { id: string; file: string; sha256: string; sql: string };
export const MIGRATIONS: readonly BundledMigration[] = ${JSON.stringify(list, null, 2)};
`;
const target = "lib/server/migrationsBundle.ts";
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== out) { console.error(`${target} is out of date: run node scripts/build-migrations.mjs`); process.exit(1); }
  console.log(`migrations bundle up to date (${list.length})`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target} (${list.length} migrations)`);
}
