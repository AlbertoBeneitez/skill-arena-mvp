#!/usr/bin/env python3
"""
Shot Gallery V12 scene (presentation art, original, generated by code; v124).

An abandoned mining station hangar seen from the gun line: a panoramic viewport onto a gas giant at the top, an
upper gallery with three hatchways behind a parapet, a catwalk with a kick plate and railing, cargo crates on the
hangar floor and an armoured barricade in front. Space creatures pop out from behind those four cover lines.

Outputs (2 px per logical unit, world x 0..390, world y -140..760):
  public/art/gallery-scene.webp   full background (cover pieces included)
  public/art/gallery-cover.webp   only the cover pieces (RGBA), drawn over the creatures

The cover lines must match GALLERY_V12.spots in lib/verified/shotGalleryCore.v12.ts.
Run: python3 scripts/render-gallery-scene.py
"""
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

S = 2                      # px per logical unit
W, H = 390 * S, 900 * S    # 780 × 1800
Y0 = -140                  # world y at the top of the image
rng = np.random.default_rng(124)

# Rows: world y of the creature centre, depth scale, cover line (creature hidden below it).
ROWS = [
    {"y": 232, "s": 0.78, "xs": [92, 195, 298]},
    {"y": 322, "s": 0.88, "xs": [74, 195, 316]},
    {"y": 420, "s": 1.00, "xs": [62, 195, 328]},
    {"y": 520, "s": 1.10, "xs": [58, 195, 332]},
]
for r in ROWS:
    r["cover"] = r["y"] + round(26 * r["s"])


def px(x, y):
    return (x * S, (y - Y0) * S)


yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
WX = xx / S
WY = yy / S + Y0


def mask_poly(points, ss=3):
    """Antialiased polygon mask (world coordinates)."""
    im = Image.new("L", (W * ss, H * ss), 0)
    ImageDraw.Draw(im).polygon([(x * S * ss, (y - Y0) * S * ss) for x, y in points], fill=255)
    return np.asarray(im.resize((W, H), Image.LANCZOS), dtype=np.float32) / 255.0


def mask_rect(x0, y0, x1, y1, ss=3):
    return mask_poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], ss)


def mask_ellipse(cx, cy, rx, ry, ss=3):
    im = Image.new("L", (W * ss, H * ss), 0)
    ImageDraw.Draw(im).ellipse([(cx - rx) * S * ss, (cy - ry - Y0) * S * ss, (cx + rx) * S * ss, (cy + ry - Y0) * S * ss], fill=255)
    return np.asarray(im.resize((W, H), Image.LANCZOS), dtype=np.float32) / 255.0


def blur(a, r):
    if a.ndim == 2:
        u8 = Image.fromarray(np.clip(a * 255, 0, 255).astype(np.uint8))
        return np.asarray(u8.filter(ImageFilter.GaussianBlur(r)), dtype=np.float32) / 255.0
    return np.stack([blur(a[..., k], r) for k in range(a.shape[2])], -1)


def value_noise(scale, octaves=4, seed=0, aniso=(1.0, 1.0)):
    """fBm value noise on the image grid; scale = feature size in px."""
    g = np.random.default_rng(seed)
    out = np.zeros((H, W), np.float32)
    amp, tot = 1.0, 0.0
    for o in range(octaves):
        sx, sy = scale * aniso[0] / 2 ** o, scale * aniso[1] / 2 ** o
        gh, gw = int(H / sy) + 3, int(W / sx) + 3
        grid = g.random((gh, gw)).astype(np.float32)
        small = Image.fromarray((grid * 255).astype(np.uint8)).resize((int(gw * sx), int(gh * sy)), Image.BICUBIC)
        arr = np.asarray(small, dtype=np.float32)[:H, :W] / 255.0
        out += arr * amp
        tot += amp
        amp *= 0.5
    return out / tot


def col(hexs):
    hexs = hexs.lstrip("#")
    return np.array([int(hexs[i:i + 2], 16) / 255 for i in (0, 2, 4)], np.float32)


def lerp(a, b, t):
    return a + (b - a) * t


img = np.zeros((H, W, 3), np.float32)
fg = np.zeros((H, W, 4), np.float32)   # premultiplied cover layer


def paint(mask, color, alpha=1.0, to_fg=False):
    global img
    m = (mask * alpha)[..., None]
    c = color if np.ndim(color) == 3 else np.broadcast_to(color, (H, W, 3))
    img = img * (1 - m) + c * m
    if to_fg:
        fg[..., :3] = fg[..., :3] * (1 - m) + c * m
        fg[..., 3:] = fg[..., 3:] * (1 - m) + m


def vgrad(y0, y1, c0, c1):
    t = np.clip((WY - y0) / max(1e-3, y1 - y0), 0, 1)[..., None]
    return lerp(col(c0), col(c1), t)


grain = value_noise(3, 2, seed=7)
brushed = value_noise(40, 3, seed=11, aniso=(6.0, 0.25))
grime = value_noise(60, 5, seed=13)
fine = value_noise(6, 3, seed=17)


def metal(base, light=1.0, dirt=0.35, brush=0.18):
    b = col(base)
    tone = (1 - dirt * (grime - 0.5) * 1.6) * (1 + brush * (brushed - 0.5)) * (1 + 0.08 * (fine - 0.5)) * light
    return np.clip(b * tone[..., None], 0, 1)


# ---------------------------------------------------------------- 1 · deep space through the viewport
space = vgrad(-140, 210, "#05081a", "#0d1430")
neb = value_noise(160, 5, seed=3)
neb2 = value_noise(90, 4, seed=4)
space += (np.clip(neb - 0.45, 0, 1) * 1.4)[..., None] * col("#3b2a6b")
space += (np.clip(neb2 - 0.55, 0, 1) * 1.6)[..., None] * col("#1f6b7a")
stars = (rng.random((H, W)) > 0.9985).astype(np.float32) * rng.random((H, W)).astype(np.float32)
space += blur(stars, 0.6)[..., None] * 2.2
# Gas giant: banded, lit from the upper left, partly below the viewport frame.
pcx, pcy, pr = 292, 178, 128
d = np.sqrt((WX - pcx) ** 2 + (WY - pcy) ** 2) / pr
inside = np.clip((1 - d) * pr * S * 0.5, 0, 1)
lat = (WY - pcy) / pr
bands = 0.5 + 0.5 * np.sin(lat * 18 + 2.2 * value_noise(50, 3, seed=21, aniso=(5, 1)) * 3)
pcol = lerp(col("#c58a52"), col("#f1d6a8"), bands[..., None]) * 0.9
pcol = lerp(pcol, col("#8a4a2c"), (np.clip(np.sin(lat * 7 + 1), 0, 1) ** 3 * 0.5)[..., None])
nz = np.sqrt(np.clip(1 - d ** 2, 0, 1))
lx, ly, lz = -0.55, -0.45, 0.70
nxv, nyv = (WX - pcx) / pr, (WY - pcy) / pr
lam = np.clip(nxv * lx + nyv * ly + nz * lz, 0, 1)
pl = pcol * (0.05 + 0.82 * lam[..., None] ** 1.1)
rim = np.clip(1 - np.abs(d - 0.985) * 45, 0, 1) * np.clip(-(nxv * 0.7 + nyv * 0.7), 0, 1)
pl += rim[..., None] * col("#ffd9a8") * 0.6
space = space * (1 - inside[..., None]) + pl * inside[..., None]
halo = np.clip(1 - np.abs(d - 1.0) * 8, 0, 1) * (d > 1)
space += halo[..., None] * col("#ff9d5c") * 0.22
mcx, mcy, mr = 70, -40, 16
md = np.sqrt((WX - mcx) ** 2 + (WY - mcy) ** 2) / mr
mlam = np.clip(((WX - mcx) * -0.6 + (WY - mcy) * -0.5) / mr + np.sqrt(np.clip(1 - md ** 2, 0, 1)) * 0.6, 0, 1)
mtex = 0.75 + 0.25 * value_noise(8, 3, seed=41)
space = space * (1 - np.clip((1 - md) * mr * S * 0.5, 0, 1)[..., None]) + (col("#c9d2dc") * (mlam * mtex)[..., None] * 0.9) * np.clip((1 - md) * mr * S * 0.5, 0, 1)[..., None]
paint(np.ones((H, W), np.float32), space)

# ---------------------------------------------------------------- 2 · hangar structure around the viewport
# Ceiling and the viewport frame (heavy girders); the viewport opening is x 14..376, y -110..196.
wall_hi = metal("#2a3446", 1.0, 0.45)
frame = np.ones((H, W), np.float32) - mask_poly([(14, -110), (376, -110), (376, 196), (14, 196)])
paint(frame, wall_hi)
# Window mullions (two diagonal struts and one horizontal).
for poly in ([(120, -110), (132, -110), (100, 196), (88, 196)], [(258, -110), (270, -110), (302, 196), (290, 196)], [(14, 40), (376, 40), (376, 47), (14, 47)]):
    m = mask_poly(poly)
    paint(m, metal("#1c2433", 0.9, 0.5))
# Bevel light along the viewport edge.
paint(blur(mask_rect(14, 192, 376, 198), 1.2), col("#9fd6ff"), 0.25)

# ---------------------------------------------------------------- 3 · upper gallery (row 0): back wall, hatchways, parapet
r0 = ROWS[0]
paint(mask_rect(0, 196, 390, 300), metal("#2b3240", 0.85, 0.5))
# panel seams
for x in range(0, 391, 48):
    paint(mask_rect(x, 196, x + 1.2, 300), col("#0b0f16"), 0.7)
for x in r0["xs"]:
    # hatchway: lit interior (amber work light inside), door slid open into the wall
    hw, top = 40 * r0["s"] + 6, r0["y"] - 52 * r0["s"]
    m = mask_poly([(x - hw, top + 8), (x - hw + 8, top), (x + hw - 8, top), (x + hw, top + 8), (x + hw, r0["cover"] + 30), (x - hw, r0["cover"] + 30)])
    inner = vgrad(top, r0["cover"] + 30, "#3a2a1c", "#120c0a")
    glow = np.exp(-(((WX - x) / (hw * 0.9)) ** 2 + ((WY - top - 8) / 22) ** 2))
    inner = inner + glow[..., None] * col("#ffb066") * 0.55
    paint(m, inner)
    # door frame
    fr = mask_poly([(x - hw - 4, top + 6), (x - hw + 6, top - 4), (x + hw - 6, top - 4), (x + hw + 4, top + 6), (x + hw + 4, r0["cover"] + 30), (x + hw, r0["cover"] + 30), (x + hw, top + 8), (x + hw - 8, top), (x - hw + 8, top), (x - hw, top + 8), (x - hw, r0["cover"] + 30), (x - hw - 4, r0["cover"] + 30)])
    paint(fr, metal("#59606c", 1.0, 0.4))
    # hazard chevrons over the door
    for k in range(5):
        cx0 = x - 20 + k * 9
        paint(mask_poly([(cx0, top - 10), (cx0 + 5, top - 10), (cx0 + 9, top - 6), (cx0 + 4, top - 6)]), col("#e0a91f"), 0.85)
# Parapet in front of the gallery (cover line row 0).
par = mask_rect(0, r0["cover"], 390, 300)
pc = metal("#3a4352", 1.05, 0.45) * vgrad(r0["cover"], 300, "#ffffff", "#9aa2b0")
paint(par, pc, to_fg=True)
paint(mask_rect(0, r0["cover"], 390, r0["cover"] + 1.6), col("#b9c6d8"), 0.8, to_fg=True)
for x in range(8, 390, 26):
    paint(mask_ellipse(x, r0["cover"] + 6, 1.3, 1.3), col("#1a1f28"), 0.9, to_fg=True)
# Red emergency strip lights on the parapet
for x in (30, 160, 230, 360):
    paint(mask_rect(x - 8, r0["cover"] + 14, x + 8, r0["cover"] + 17), col("#ff6b5b"), 1.0, to_fg=True)
    paint(blur(mask_rect(x - 14, r0["cover"] + 10, x + 14, r0["cover"] + 22), 6), col("#ff2a2a"), 0.45, to_fg=False)

# ---------------------------------------------------------------- 4 · middle level (row 1): back wall + catwalk
r1 = ROWS[1]
paint(mask_rect(0, 300, 390, 375), metal("#232a36", 0.8, 0.55))
# pipes along the back wall
for yp, rad, c in ((308, 3.5, "#4a5262"), (318, 2.4, "#6b5a3a"), (360, 4.5, "#3d4554")):
    m = mask_rect(0, yp - rad, 390, yp + rad)
    shade = np.clip(1 - ((WY - yp) / rad) ** 2, 0, 1) ** 0.5
    paint(m, col(c) * (0.45 + 0.75 * shade)[..., None])
# catwalk railing (thin, in front): top rail and posts
rail_top = r1["y"] - 18
paint(mask_rect(0, rail_top, 390, rail_top + 2.4), metal("#9aa3b0", 1.15, 0.3), to_fg=True)
paint(mask_rect(0, rail_top + 12, 390, rail_top + 13.4), metal("#7d8696", 1.0, 0.3), to_fg=True)
for x in range(4, 391, 42):
    paint(mask_rect(x, rail_top, x + 2.6, r1["cover"]), metal("#8a93a2", 1.0, 0.3), to_fg=True)
# kick plate (cover line row 1) with diamond tread
kp = mask_rect(0, r1["cover"], 390, 378)
tread = 0.85 + 0.15 * (np.sin(WX * 1.4 + WY * 1.4) * np.sin(WX * 1.4 - WY * 1.4) > 0.6)
paint(kp, metal("#4b5363", 1.0, 0.5) * tread[..., None] * vgrad(r1["cover"], 378, "#ffffff", "#7d8595"), to_fg=True)
paint(mask_rect(0, r1["cover"], 390, r1["cover"] + 1.6), col("#c9d4e4"), 0.7, to_fg=True)
for k in range(0, 390, 30):
    paint(mask_poly([(k, 370), (k + 15, 370), (k + 21, 378), (k + 6, 378)]), col("#d9a21c"), 0.85, to_fg=True)

# ---------------------------------------------------------------- 5 · hangar floor + back wall (row 2) and crates
r2 = ROWS[2]
paint(mask_rect(0, 378, 390, 470), vgrad(378, 470, "#1a2130", "#2a3240"))
# hangar back wall details: big bay door with stripes, light panels
paint(mask_rect(130, 380, 260, 440), metal("#30394a", 0.9, 0.5))
for k in range(8):
    paint(mask_rect(132, 384 + k * 7, 258, 386 + k * 7), col("#141a24"), 0.7)
for x in (40, 350):
    paint(mask_rect(x - 14, 386, x + 14, 392), col("#bfe8ff"), 0.9)
    paint(blur(mask_rect(x - 20, 386, x + 20, 400), 8), col("#7fd4ff"), 0.35)
# crates (cover line row 2): three stacks with stencils
crate_cols = ["#5a6b3a", "#6b4a2a", "#3a5a6b"]
for i, x in enumerate(r2["xs"]):
    w = 52
    top = r2["cover"]
    body = mask_rect(x - w, top, x + w, 500)
    c = metal(crate_cols[i], 1.0, 0.55, 0.1) * vgrad(top, 500, "#ffffff", "#8a8f96")
    paint(body, c, to_fg=True)
    # lid lip and bands
    paint(mask_rect(x - w - 2, top - 3, x + w + 2, top + 4), metal("#9097a3", 1.1, 0.4), to_fg=True)
    for bx in (x - w + 10, x + w - 14):
        paint(mask_rect(bx, top + 4, bx + 4, 500), metal("#2b2f36", 1.0, 0.4), 0.9, to_fg=True)
    # stencil number
    paint(mask_rect(x - 18, top + 18, x + 18, top + 30), col("#e6e0cf"), 0.55, to_fg=True)
    paint(mask_rect(x - 14, top + 21, x + 14, top + 27), col(crate_cols[i]) * 0.6, 0.8, to_fg=True)
paint(blur(mask_rect(0, 498, 390, 506), 4), col("#000000"), 0.5)

# ---------------------------------------------------------------- 6 · front: floor plates and armoured barricade (row 3)
r3 = ROWS[3]
paint(mask_rect(0, 500, 390, 760), vgrad(500, 760, "#262e3c", "#0d1118"))
# floor plate seams in perspective (vanishing point high centre)
for k in range(-6, 7):
    xb = 195 + k * 70
    paint(mask_poly([(195 + k * 22 - 0.6, 500), (195 + k * 22 + 0.6, 500), (xb + 1.2, 760), (xb - 1.2, 760)]), col("#06080c"), 0.6)
# barricade: angled armour panels (cover line row 3)
bt = r3["cover"]
for i, x in enumerate(r3["xs"]):
    w = 62
    poly = [(x - w, bt + 6), (x - w + 10, bt), (x + w - 10, bt), (x + w, bt + 6), (x + w + 6, 640), (x - w - 6, 640)]
    m = mask_poly(poly)
    c = metal("#454c58", 1.05, 0.6) * vgrad(bt, 640, "#ffffff", "#6c727c")
    paint(m, c, to_fg=True)
    paint(mask_poly([(x - w + 10, bt), (x + w - 10, bt), (x + w - 8, bt + 2), (x - w + 8, bt + 2)]), col("#d6deea"), 0.8, to_fg=True)
    # hazard stripes band
    band = mask_rect(x - w, bt + 20, x + w, bt + 32)
    stripes = ((np.floor((WX + WY) / 8) % 2) == 0).astype(np.float32)
    paint(band * stripes, col("#e3ad1e"), 0.9, to_fg=True)
    paint(band * (1 - stripes), col("#15181d"), 0.9, to_fg=True)
    # scorch and scratches
    paint(mask_ellipse(x + 20 - i * 14, bt + 52, 16, 9) * grime, col("#0b0b0b"), 0.5, to_fg=True)
# lower front floor (part of the cover layer so marks there stay on top)
paint(mask_rect(0, 640, 390, 760), vgrad(640, 760, "#20262f", "#07090d"), to_fg=True)
for k in range(0, 390, 36):
    paint(mask_poly([(k, 650), (k + 18, 650), (k + 26, 660), (k + 8, 660)]), col("#caa12a"), 0.55, to_fg=True)

# ---------------------------------------------------------------- 6b · dressing: contact shadows, cables, signage, fog
def shade_band(y0, y1, a):
    t = np.clip((WY - y0) / (y1 - y0), 0, 1)
    return (1 - t) * (WY >= y0) * (WY <= y1) * a
img = img * (1 - shade_band(300, 326, 0.55)[..., None])          # under the upper gallery floor
img = img * (1 - shade_band(378, 404, 0.6)[..., None])           # under the catwalk
img = img * (1 - shade_band(196, 214, 0.45)[..., None])          # under the viewport frame
# hanging cables (catenaries)
for (xa, xb, ya, sag, wdt) in ((0, 170, 388, 16, 1.6), (150, 390, 384, 22, 2.0), (20, 260, 202, 10, 1.3)):
    xs_ = np.linspace(xa, xb, 400)
    t = (xs_ - xa) / (xb - xa)
    ys_ = ya + sag * 4 * t * (1 - t)
    cm = np.zeros((H, W), np.float32)
    im_ = Image.new("L", (W * 2, H * 2), 0)
    ImageDraw.Draw(im_).line([(x * S * 2, (y - Y0) * S * 2) for x, y in zip(xs_, ys_)], fill=255, width=int(wdt * S * 2))
    cm = np.asarray(im_.resize((W, H), Image.LANCZOS), dtype=np.float32) / 255
    paint(cm, col("#07090d"), 0.95)
# stencil "07" on the bay door (block digits)
def block_digit(ox, oy, w, h, segs, t=5):
    P = {"a": (ox, oy, ox + w, oy + t), "d": (ox, oy + h - t, ox + w, oy + h), "g": (ox, oy + h / 2 - t / 2, ox + w, oy + h / 2 + t / 2),
         "f": (ox, oy, ox + t, oy + h / 2), "e": (ox, oy + h / 2, ox + t, oy + h), "b": (ox + w - t, oy, ox + w, oy + h / 2), "c": (ox + w - t, oy + h / 2, ox + w, oy + h)}
    for k in segs:
        paint(mask_rect(*P[k]), col("#c9b98a"), 0.42)
block_digit(166, 386, 24, 44, "abcdef")
block_digit(198, 386, 24, 44, "abc")
# low fog banks (hangar floor and front)
for yb, hgt, a, sd in ((470, 30, 0.2, 51), (596, 44, 0.16, 52), (408, 16, 0.1, 53)):
    n = value_noise(70, 4, seed=sd, aniso=(3, 1))
    band = np.exp(-((WY - yb) / hgt) ** 2) * (0.4 + 0.9 * n) * a
    img = img * (1 - band[..., None]) + col("#4f6a90") * band[..., None]
# floor reflections of the hangar lights (wet floor streaks)
for x_ in (40, 350, 195):
    refl = np.exp(-((WX - x_) / 10) ** 2) * np.exp(-((WY - 520) / 40) ** 2) * 0.22 * (WY > 500)
    img = img + refl[..., None] * col("#9fdcff")

# ---------------------------------------------------------------- 7 · light: shafts, haze, grading
# volumetric shafts from the viewport (upper left), soft
shaft = np.zeros((H, W), np.float32)
for ox, wdt, a in ((80, 26, 0.5), (150, 18, 0.35), (210, 34, 0.28)):
    dx = (WX - ox) - (WY - 0) * 0.32
    shaft += np.exp(-(dx / wdt) ** 2) * a * np.clip((WY - 60) / 120, 0, 1) * np.clip((720 - WY) / 400, 0, 1)
shaft *= 0.55 + 0.45 * value_noise(30, 3, seed=31, aniso=(0.4, 3))
img = img + shaft[..., None] * col("#8fc8ff") * 0.22
# depth haze: thicker toward the back rows
haze = np.clip(1 - (WY - 180) / 420, 0, 1) * 0.1 * (WY > 196)
img = img * (1 - haze[..., None]) + col("#5c7aa0") * haze[..., None]
# warm work lights from the sides
for lx_, ly_, c, r in ((0, 420, "#ff9a4a", 160), (390, 330, "#ff7a3a", 140), (195, 760, "#2a6bff", 260)):
    glow = np.exp(-(((WX - lx_) ** 2 + (WY - ly_) ** 2) / (r * r)))
    img = img + glow[..., None] * col(c) * 0.16
# film grade: teal shadows / warm highlights, vignette, grain
lum = img.mean(-1, keepdims=True)
img = img + (col("#0a2a33") - img) * np.clip(0.35 - lum, 0, 0.35) * 0.4 + (col("#ffd0a0") - img) * np.clip(lum - 0.55, 0, 1) * 0.15
vig = np.clip(1 - (((WX - 195) / 260) ** 2 + ((WY - 320) / 520) ** 2) ** 1.4 * 0.55, 0.35, 1)
img = img * vig[..., None]
bright = np.clip(img - 0.62, 0, 1)
img = img + blur(bright, 10) * 0.9 + blur(bright, 3) * 0.5
img = np.clip(img, 0, 1) ** 1.18
img = img + (grain - 0.5)[..., None] * 0.035
img = np.clip(img, 0, 1)

# The cover layer receives the same shafts and grade so it matches the background exactly where it is opaque.
alpha = np.clip(fg[..., 3:], 0, 1)
cover_rgb = img
cover = np.concatenate([cover_rgb, alpha], -1)

Image.fromarray((img * 255).astype(np.uint8)).save("public/art/gallery-scene.webp", quality=86, method=6)
Image.fromarray((np.clip(cover, 0, 1) * 255).astype(np.uint8), "RGBA").save("public/art/gallery-cover.webp", quality=88, method=6)
print("rows", [(r["y"], r["cover"]) for r in ROWS])
